/**
 * @param {*} value - Anything.
 * @returns {boolean} Whether it is a JSON object rather than an array or null.
 */
function isPlainObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/**
 * One object being read: it knows where the object sits in the request body,
 * which of its keys the schema has asked about, and where to report a fault.
 *
 * Reading a key and declaring it are separate: `declare` is the one method
 * that changes the reader, and what was never declared is what `rejectUnknown`
 * refuses at the end.
 */
class ObjectReader {
  /**
   * @param {Object} value - The object being read.
   * @param {string} path - Its JSON path in the request body.
   * @param {HeroValidationErrors} errors - The run's collector.
   */
  constructor(value, path, errors) {
    this.value = value;
    this.path = path;
    this.errors = errors;
    this.declaredKeys = new Set();
  }

  /**
   * Records that the schema knows these keys, whether or not they are there.
   *
   * @param {...string} keys - Keys of the object.
   */
  declare(...keys) {
    keys.forEach((key) => this.declaredKeys.add(key));
  }

  /**
   * Whether the key carries a value. An empty string, `null` and `undefined`
   * all read as "not given": that is how the editor clears a field.
   *
   * @param {string} key - Key of the object.
   * @returns {boolean}
   */
  given(key) {
    const value = this.value[key];
    return value !== undefined && value !== null && value !== "";
  }

  /**
   * @param {string} key - Key of the object.
   * @returns {*} The stored value.
   */
  raw(key) {
    return this.value[key];
  }

  /**
   * A reader for the object behind one of the keys. The key must be declared
   * and given; a value that is not an object is a fault here.
   *
   * @param {string} key - Key of the object.
   * @returns {?ObjectReader} The reader, or null when the value is no object.
   */
  child(key) {
    const path = childPath(this.path, key);

    if (!isPlainObject(this.raw(key))) {
      this.errors.add(path, ERROR_CODES.format, { format: "object" });
      return null;
    }

    return new ObjectReader(this.raw(key), path, this.errors);
  }

  /**
   * Records a fault at one of the object's keys.
   *
   * @param {string} key - Key of the object.
   * @param {string} code - Code of the contract's error vocabulary.
   * @param {Object} [params] - What the code needs to be understood.
   */
  fail(key, code, params) {
    this.errors.add(childPath(this.path, key), code, params);
  }

  /**
   * Refuses every key the schema never declared.
   */
  rejectUnknown() {
    for (const key of Object.keys(this.value)) {
      if (!this.declaredKeys.has(key)) {
        this.errors.add(childPath(this.path, key), ERROR_CODES.unknownField);
      }
    }
  }
}

/**
 * A value out of a fixed set. Without a fallback the key is required.
 *
 * @param {ObjectReader} reader - The object being read.
 * @param {string} key - Key of the object.
 * @param {Array<*>} allowed - The values of the enum.
 * @param {*} [fallback] - Default when the key is not given.
 * @returns {*} The value, the fallback, or null on a fault.
 */
function readEnum(reader, key, allowed, fallback) {
  reader.declare(key);

  if (!reader.given(key)) {
    if (fallback === undefined) {
      reader.fail(key, ERROR_CODES.required);
      return null;
    }
    return fallback;
  }

  const value = reader.raw(key);

  if (!allowed.includes(value)) {
    reader.fail(key, ERROR_CODES.enum, { allowed });
    return null;
  }

  return value;
}

/**
 * A boolean switch with a default.
 *
 * @param {ObjectReader} reader - The object being read.
 * @param {string} key - Key of the object.
 * @param {boolean} fallback - Default when the key is not given.
 * @returns {boolean} The value or the fallback.
 */
function readBoolean(reader, key, fallback) {
  reader.declare(key);

  if (!reader.given(key)) {
    return fallback;
  }

  const value = reader.raw(key);

  if (typeof value !== "boolean") {
    reader.fail(key, ERROR_CODES.format, { format: "boolean" });
    return fallback;
  }

  return value;
}

/**
 * A string value.
 *
 * @param {ObjectReader} reader - The object being read.
 * @param {string} key - Key of the object.
 * @param {boolean} required - Whether an absent key is a fault.
 * @returns {?string} The value, or null when absent or faulty.
 */
function readString(reader, key, required) {
  reader.declare(key);

  if (!reader.given(key)) {
    if (required) {
      reader.fail(key, ERROR_CODES.required);
    }
    return null;
  }

  const value = reader.raw(key);

  if (typeof value !== "string") {
    reader.fail(key, ERROR_CODES.format, { format: "string" });
    return null;
  }

  return value;
}

/**
 * A colour of the Background: `#rrggbb`, no shorthand and no alpha.
 *
 * @param {ObjectReader} reader - The object being read.
 * @param {string} key - Key of the object.
 * @param {boolean} required - Whether an absent key is a fault.
 * @returns {?string} The colour, or null when absent or faulty.
 */
function readHexColor(reader, key, required) {
  const value = readString(reader, key, required);

  if (value === null) {
    return null;
  }

  if (!HEX_COLOR.test(value)) {
    reader.fail(key, ERROR_CODES.format, { format: "hex" });
    return null;
  }

  return value;
}

/**
 * A whole percentage, 0 to 100.
 *
 * @param {ObjectReader} reader - The object being read.
 * @param {string} key - Key of the object.
 * @param {number} fallback - Default when the key is not given.
 * @returns {number} The value or the fallback.
 */
function readPercentage(reader, key, fallback) {
  reader.declare(key);

  if (!reader.given(key)) {
    return fallback;
  }

  const value = reader.raw(key);

  if (!Number.isInteger(value) || value < 0 || value > 100) {
    reader.fail(key, ERROR_CODES.format, { format: "percentage" });
    return fallback;
  }

  return value;
}

/**
 * A media reference of the Shared contract. Every site that takes one - the
 * image Background, an image Block - requires it, so an absent key is a fault
 * here. What the medium behind it has to be is not decided here: the
 * reference is collected and checked against the media library once the shape
 * of the whole object is known.
 *
 * @param {ObjectReader} reader - The object carrying the reference.
 * @param {string} key - Key the reference sits at.
 * @param {Array<{field: string, reference: Object}>} references - Where the
 *   reference is collected for the media check.
 * @returns {?Object} The reference as it is stored, or null on a fault.
 */
function readMediaReference(reader, key, references) {
  reader.declare(key);

  if (!reader.given(key)) {
    reader.fail(key, ERROR_CODES.required);
    return null;
  }

  const reference = reader.child(key);

  if (!reference) {
    return null;
  }

  // The export adds these three; refusing them would stop an enriched
  // reference from coming back through the editor unchanged.
  reference.declare(...MEDIA_REFERENCE_DERIVED_KEYS);

  const source = readEnum(reference, "source", MEDIA_REFERENCE_SOURCES);
  // An external reference carries no media id and is refused as a whole by the
  // media check, which names the reason; demanding an id here would answer the
  // wrong fault.
  const mediaId = readString(
    reference,
    "mediaId",
    source === MEDIA_REFERENCE_SOURCE.MEDIA,
  );

  reference.rejectUnknown();

  if (source === null) {
    return null;
  }

  const stored = mediaId ? { source, mediaId } : { source };
  references.push({ field: reference.path, reference: stored });

  return stored;
}

/**
 * The focal point of an image Background.
 *
 * @param {ObjectReader} reader - The Background being read.
 * @returns {{x: number, y: number}} The point, defaults filled.
 */
function readFocalPoint(reader) {
  reader.declare("focalPoint");

  if (!reader.given("focalPoint")) {
    return { ...DEFAULT_FOCAL_POINT };
  }

  const point = reader.child("focalPoint");

  if (!point) {
    return { ...DEFAULT_FOCAL_POINT };
  }

  const focalPoint = {
    x: readPercentage(point, "x", DEFAULT_FOCAL_POINT.x),
    y: readPercentage(point, "y", DEFAULT_FOCAL_POINT.y),
  };
  point.rejectUnknown();

  return focalPoint;
}

/**
 * One entry of the overlay — the colour painted over the image and how far it
 * darkens it.
 *
 * @param {ObjectReader} reader - The overlay being read.
 * @param {string} key - `light` or `dark`.
 * @returns {{color: string, opacity: number}} The entry, defaults filled.
 */
function readOverlayEntry(reader, key) {
  const entry = reader.child(key);

  if (!entry) {
    return { ...DEFAULT_OVERLAY_ENTRY };
  }

  const overlayEntry = {
    color: readHexColor(entry, "color", false) ?? DEFAULT_OVERLAY_ENTRY.color,
    opacity: readPercentage(entry, "opacity", DEFAULT_OVERLAY_ENTRY.opacity),
  };
  entry.rejectUnknown();

  return overlayEntry;
}

/**
 * The overlay of an image Background. An overlay that is not given at all is
 * the contract's default; one that is given has to name its light entry, the
 * one the dark mode falls back to.
 *
 * @param {ObjectReader} reader - The Background being read.
 * @returns {Object} The overlay, defaults filled.
 */
function readOverlay(reader) {
  reader.declare("overlay");

  if (!reader.given("overlay")) {
    return { light: { ...DEFAULT_OVERLAY_ENTRY } };
  }

  const overlay = reader.child("overlay");

  if (!overlay) {
    return { light: { ...DEFAULT_OVERLAY_ENTRY } };
  }

  overlay.declare("light", "dark");

  let light = null;
  if (overlay.given("light")) {
    light = readOverlayEntry(overlay, "light");
  } else {
    overlay.fail("light", ERROR_CODES.required);
  }

  const dark = overlay.given("dark") ? readOverlayEntry(overlay, "dark") : null;

  overlay.rejectUnknown();

  return dark ? { light, dark } : { light };
}

/**
 * The three families of the Background, each reading the half of the object
 * that belongs to it. The keys are the values of `type`.
 */
const BACKGROUND_FAMILIES = Object.freeze({
  variant: (reader) => ({
    variant: readEnum(reader, "variant", BACKGROUND_VARIANTS),
    orbs: readBoolean(reader, "orbs", DEFAULT_BACKGROUND.orbs),
    noise: readBoolean(reader, "noise", DEFAULT_BACKGROUND.noise),
    intensity: readEnum(
      reader,
      "intensity",
      BACKGROUND_INTENSITIES,
      DEFAULT_BACKGROUND.intensity,
    ),
  }),

  color: (reader) => {
    const light = readHexColor(reader, "light", true);
    // The dark colour falls back to the light one at render time, so an absent
    // key is the whole answer and no default is written for it.
    const dark = readHexColor(reader, "dark", false);

    return dark ? { light, dark } : { light };
  },

  image: (reader, references) => ({
    image: readMediaReference(reader, "image", references),
    focalPoint: readFocalPoint(reader),
    overlay: readOverlay(reader),
  }),
});

const BACKGROUND_TYPES = Object.freeze(Object.keys(BACKGROUND_FAMILIES));

/**
 * Reads one Background into its stored form, recording every fault it finds.
 *
 * @param {*} input - What the client sent.
 * @param {string} path - Its JSON path in the request body.
 * @param {HeroValidationErrors} errors - The run's collector.
 * @param {Array<{field: string, reference: Object}>} references - Where media
 *   references are collected for the media check.
 * @returns {?Object} The stored Background, or null when it cannot be read.
 */
function readBackground(input, path, errors, references) {
  if (!isPlainObject(input)) {
    errors.add(path, ERROR_CODES.format, { format: "object" });
    return null;
  }

  const reader = new ObjectReader(input, path, errors);

  readEnum(reader, "version", [BACKGROUND_VERSION]);
  const type = readEnum(reader, "type", BACKGROUND_TYPES);

  // Without the family nothing below is known, so the read stops here rather
  // than calling every remaining key unknown.
  if (type === null) {
    return null;
  }

  const background = {
    version: BACKGROUND_VERSION,
    type,
    ...BACKGROUND_FAMILIES[type](reader, references),
  };

  reader.rejectUnknown();

  return background;
}

/**
 * The stored form of a Background: every default filled, every derived media
 * key dropped, every fault answered at its JSON path.
 *
 * @param {?Object} input - What the client sent. `null` is the reset to the
 *   default Background and passes straight through — the default is filled in
 *   on the way out, so a Background that was never touched keeps following
 *   whatever the default becomes.
 * @param {string} [field] - Where the Background sits in the request body:
 *   `background` on the hero-layout routes, `branding.background` on the
 *   instance PUT. Every reported path starts here.
 * @returns {Promise<?Object>} The Background as it is stored.
 * @throws {ValidationError} With one detail per fault, JSON paths as fields.
 */
async function normalizeBackground(input, field = "background") {
  if (input === null || input === undefined) {
    return null;
  }

  const errors = new HeroValidationErrors();
  const references = [];

  const background = readBackground(input, field, errors, references);

  // The media library is only asked once the shape is sound: a lookup for a
  // reference that is malformed anyway would answer the wrong fault.
  errors.throwIfAny();
  await MediaReferenceGuard.assertHeroLayoutStorable(references);

  return background;
}

/**
 * A localised string of the Shared contract: `de` has to be there, an empty
 * `en` reads as absent, and every locale is capped on its own.
 *
 * @param {ObjectReader} reader - The Block carrying the string.
 * @param {string} key - Key the string sits at.
 * @param {?number} maxLength - The cap per locale, or null when the caller
 *   measures the length itself — rich text is capped after sanitising.
 * @returns {?Object} The string as it is stored, or null when the key carries
 *   no object at all.
 */
function readLocalizedString(reader, key, maxLength) {
  reader.declare(key);

  if (!reader.given(key)) {
    reader.fail(key, ERROR_CODES.required);
    return null;
  }

  const localized = reader.child(key);

  if (!localized) {
    return null;
  }

  const stored = {};

  for (const locale of LOCALES) {
    const value = readString(localized, locale, locale === REQUIRED_LOCALE);

    if (value === null) {
      continue;
    }

    if (maxLength !== null && value.length > maxLength) {
      localized.fail(locale, ERROR_CODES.maxLength, {
        max: maxLength,
        actual: value.length,
      });
      continue;
    }

    stored[locale] = value;
  }

  localized.rejectUnknown();

  return stored;
}

/**
 * The HTML of a rich-text Block. Its locales are read like any localised
 * string and then handed to the sanitiser, which is asynchronous and carries
 * the two length rules of the contract, so they are collected here and run
 * once the shape of the whole layout is known.
 *
 * @param {ObjectReader} reader - The Block being read.
 * @param {Array<Object>} richTexts - Where the locales are collected.
 * @returns {?Object} The string as it is stored, still unsanitised.
 */
function readRichText(reader, richTexts) {
  const stored = readLocalizedString(reader, "html", null);

  for (const locale of Object.keys(stored ?? {})) {
    richTexts.push({
      field: childPath(childPath(reader.path, "html"), locale),
      html: stored[locale],
      target: stored,
      locale,
    });
  }

  return stored;
}

/**
 * A colour of the Hero: one of the named tokens the site takes or a
 * `#rrggbb`. Which tokens those are differs — a text Block has its own
 * vocabulary, a Panel its own — and a Background takes hex alone.
 *
 * @param {ObjectReader} reader - The object being read.
 * @param {string} key - Key of the colour.
 * @param {Array<string>} tokens - The named colours of the site.
 * @param {string} fallback - Default when the key is not given.
 * @returns {string} The colour or the fallback.
 */
function readColor(reader, key, tokens, fallback) {
  const value = readString(reader, key, false);

  if (value === null) {
    return fallback;
  }

  if (!tokens.includes(value) && !HEX_COLOR.test(value)) {
    reader.fail(key, ERROR_CODES.format, { format: "color" });
    return fallback;
  }

  return value;
}

/**
 * The Panel one of the two legacy words stands for.
 *
 * @param {string} word - `none` or `translucent`.
 * @returns {?Object} A fresh Panel, or null for no Panel.
 */
function legacyPanel(word) {
  const panel = LEGACY_PANELS[word];

  return panel ? { ...panel } : null;
}

/**
 * The Panel of a Block: `null` for no Panel, or the surface it paints behind
 * itself with every key at its „Glas“ default. The two legacy words are taken
 * here and translated, so an admin that has not caught up yet still saves a
 * layout in the amended form.
 *
 * @param {ObjectReader} reader - The Block being read.
 * @returns {?Object} The Panel as it is stored, or null for no Panel.
 */
function readPanel(reader) {
  reader.declare("panel");

  if (!reader.given("panel")) {
    return BLOCK_DEFAULTS.panel;
  }

  const raw = reader.raw("panel");

  if (typeof raw === "string") {
    if (!Object.hasOwn(LEGACY_PANELS, raw)) {
      // Any other string is a Panel of the wrong shape rather than an unknown
      // word: what the contract names here is an object.
      reader.fail("panel", ERROR_CODES.format, { format: "object" });
      return null;
    }

    return legacyPanel(raw);
  }

  const panel = reader.child("panel");

  if (!panel) {
    return null;
  }

  const stored = {
    color: readColor(panel, "color", PANEL_COLOR_TOKENS, DEFAULT_PANEL.color),
    opacity: readPercentage(panel, "opacity", DEFAULT_PANEL.opacity),
    radius: readEnum(panel, "radius", PANEL_RADII, DEFAULT_PANEL.radius),
    blur: readBoolean(panel, "blur", DEFAULT_PANEL.blur),
  };
  panel.rejectUnknown();

  return stored;
}

/**
 * The Panel a stored Block carries, in the form of the amended contract. A
 * Block written before the Panel became an object still holds one of the two
 * words; the export translates them so the storefront never meets a word it
 * no longer knows.
 *
 * @param {*} panel - The stored Panel: null, an object, or a legacy word.
 * @returns {?Object} The Panel as it goes out.
 */
function exportPanel(panel) {
  if (typeof panel === "string") {
    return legacyPanel(panel);
  }

  return panel ?? null;
}

/**
 * One axis of a Block's offset. It is a length in rem rather than a count of
 * steps: −3…3 on the 0.5 grid. The grid is read as `value * 2` being whole,
 * which needs no epsilon — a half is exact in binary floating point.
 *
 * @param {ObjectReader} reader - The offset being read.
 * @param {string} key - `x` or `y`.
 * @param {number} fallback - Default when the axis is not given.
 * @returns {number} The displacement in rem, or the fallback.
 */
function readOffsetAxis(reader, key, fallback) {
  reader.declare(key);

  if (!reader.given(key)) {
    return fallback;
  }

  const value = reader.raw(key);

  if (
    !Number.isFinite(value) ||
    value < -MAX_OFFSET ||
    value > MAX_OFFSET ||
    !Number.isInteger(value * 2)
  ) {
    reader.fail(key, ERROR_CODES.format, { format: "offset_step" });
    return fallback;
  }

  return value;
}

/**
 * The offset of a Block: a pure translation out of the place its Zone gives
 * it, positive `x` to the right and positive `y` down.
 *
 * @param {ObjectReader} reader - The Block being read.
 * @returns {{x: number, y: number}} The offset, defaults filled.
 */
function readOffset(reader) {
  reader.declare("offset");

  if (!reader.given("offset")) {
    return { ...DEFAULT_OFFSET };
  }

  const offset = reader.child("offset");

  if (!offset) {
    return { ...DEFAULT_OFFSET };
  }

  const stored = {
    x: readOffsetAxis(offset, "x", DEFAULT_OFFSET.x),
    y: readOffsetAxis(offset, "y", DEFAULT_OFFSET.y),
  };
  offset.rejectUnknown();

  return stored;
}

/**
 * The id of a Block: what the editor generated for it, and what a
 * `duplicate_id` is measured against.
 *
 * @param {ObjectReader} reader - The Block being read.
 * @returns {?string} The id, or null when absent or malformed.
 */
function readBlockId(reader) {
  const id = readString(reader, "id", true);

  if (id === null) {
    return null;
  }

  if (!BLOCK_ID.test(id)) {
    reader.fail("id", ERROR_CODES.format, { format: "block_id" });
    return null;
  }

  return id;
}

/**
 * The three kinds of Block, each reading the half of the object that belongs
 * to it. The keys are the values of `type`.
 */
const BLOCK_FAMILIES = Object.freeze({
  text: (reader) => ({
    text: readLocalizedString(reader, "text", MAX_TEXT_LENGTH),
    size: readEnum(reader, "size", TEXT_SIZES, DEFAULT_TEXT_SIZE),
    color: readColor(reader, "color", CONTENT_COLOR_TOKENS, "default"),
    weight: readEnum(reader, "weight", TEXT_WEIGHTS, "normal"),
    shadow: readBoolean(reader, "shadow", false),
  }),

  richtext: (reader, { richTexts }) => ({
    html: readRichText(reader, richTexts),
    size: readEnum(reader, "size", TEXT_SIZES, DEFAULT_TEXT_SIZE),
    color: readColor(reader, "color", CONTENT_COLOR_TOKENS, "default"),
    shadow: readBoolean(reader, "shadow", false),
  }),

  image: (reader, { references }) => ({
    image: readMediaReference(reader, "image", references),
    alt: readLocalizedString(reader, "alt", MAX_TEXT_LENGTH),
    maxHeight: readEnum(reader, "maxHeight", IMAGE_MAX_HEIGHTS, "md"),
    invertInDarkMode: readBoolean(reader, "invertInDarkMode", false),
  }),
});

const BLOCK_TYPES = Object.freeze(Object.keys(BLOCK_FAMILIES));

/**
 * Reads one Block into its stored form: the common fields of the contract,
 * then the half that belongs to its type.
 *
 * @param {*} input - What the client sent.
 * @param {string} path - Its JSON path in the request body.
 * @param {HeroValidationErrors} errors - The run's collector.
 * @param {{references: Array, richTexts: Array}} collectors - What is checked
 *   and sanitised once the whole layout has been read.
 * @returns {?Object} The stored Block, or null when it cannot be read.
 */
function readBlock(input, path, errors, collectors) {
  if (!isPlainObject(input)) {
    errors.add(path, ERROR_CODES.format, { format: "object" });
    return null;
  }

  const reader = new ObjectReader(input, path, errors);

  const id = readBlockId(reader);
  const type = readEnum(reader, "type", BLOCK_TYPES);
  const zone = readEnum(reader, "zone", BLOCK_ZONES);

  // Without the type the content field is unknown, so the read stops here
  // rather than calling every remaining key unknown.
  if (type === null) {
    return null;
  }

  const block = {
    id,
    type,
    zone,
    outerSpacing: readEnum(
      reader,
      "outerSpacing",
      BLOCK_SPACINGS,
      BLOCK_DEFAULTS.outerSpacing,
    ),
    innerSpacing: readEnum(
      reader,
      "innerSpacing",
      BLOCK_SPACINGS,
      BLOCK_DEFAULTS.innerSpacing,
    ),
    width: readEnum(reader, "width", BLOCK_WIDTHS, BLOCK_DEFAULTS.width),
    align: readEnum(reader, "align", BLOCK_ALIGNMENTS, BLOCK_DEFAULTS.align),
    panel: readPanel(reader),
    offset: readOffset(reader),
    layer: readEnum(reader, "layer", BLOCK_LAYERS, BLOCK_DEFAULTS.layer),
    homeOnly: readBoolean(reader, "homeOnly", BLOCK_DEFAULTS.homeOnly),
    hideOnMobile: readBoolean(
      reader,
      "hideOnMobile",
      BLOCK_DEFAULTS.hideOnMobile,
    ),
    ...BLOCK_FAMILIES[type](reader, collectors),
  };

  reader.rejectUnknown();

  return block;
}

/**
 * The Blocks of a layout, in the order they were sent — which is the stacking
 * order inside a Zone and the reading order on mobile. An id that was already
 * used is refused at the Block that repeats it, so the editor marks the
 * second one.
 *
 * @param {ObjectReader} reader - The layout being read.
 * @param {{references: Array, richTexts: Array}} collectors - What is checked
 *   and sanitised once the whole layout has been read.
 * @returns {Array<?Object>} The stored Blocks.
 */
function readBlocks(reader, collectors) {
  reader.declare("blocks");

  const raw = reader.raw("blocks");

  // An empty array is a layout without Blocks and passes; only a missing one
  // is a fault, so the "not given" rule of the other keys does not apply.
  if (raw === undefined || raw === null) {
    reader.fail("blocks", ERROR_CODES.required);
    return [];
  }

  if (!Array.isArray(raw)) {
    reader.fail("blocks", ERROR_CODES.format, { format: "array" });
    return [];
  }

  if (raw.length > MAX_BLOCKS) {
    reader.fail("blocks", ERROR_CODES.maxItems, {
      max: MAX_BLOCKS,
      actual: raw.length,
    });
  }

  const path = childPath(reader.path, "blocks");
  const ids = new Set();

  return raw.map((entry, index) => {
    const blockPath = elementPath(path, index);
    const block = readBlock(entry, blockPath, reader.errors, collectors);

    if (block?.id) {
      if (ids.has(block.id)) {
        reader.errors.add(childPath(blockPath, "id"), ERROR_CODES.duplicateId);
      }
      ids.add(block.id);
    }

    return block;
  });
}

/**
 * Reads one Hero Layout into its stored form, recording every fault it finds.
 *
 * @param {*} input - What the client sent.
 * @param {string} path - Its JSON path in the request body.
 * @param {HeroValidationErrors} errors - The run's collector.
 * @param {{references: Array, richTexts: Array}} collectors - What is checked
 *   and sanitised once the whole layout has been read.
 * @returns {?Object} The stored layout, or null when it cannot be read.
 */
function readHeroLayout(input, path, errors, collectors) {
  if (!isPlainObject(input)) {
    errors.add(path, ERROR_CODES.format, { format: "object" });
    return null;
  }

  const reader = new ObjectReader(input, path, errors);

  readEnum(reader, "version", [HERO_LAYOUT_VERSION]);

  const layout = {
    version: HERO_LAYOUT_VERSION,
    height: readEnum(
      reader,
      "height",
      HERO_HEIGHTS,
      HERO_LAYOUT_DEFAULTS.height,
    ),
    mobileHeight: readEnum(
      reader,
      "mobileHeight",
      HERO_HEIGHTS,
      HERO_LAYOUT_DEFAULTS.mobileHeight,
    ),
    compactHeight: readEnum(
      reader,
      "compactHeight",
      HERO_HEIGHTS,
      HERO_LAYOUT_DEFAULTS.compactHeight,
    ),
    blocks: readBlocks(reader, collectors),
  };

  reader.rejectUnknown();

  return layout;
}

/**
 * Runs every locale of every rich-text Block through the sanitiser and writes
 * the result back where it was read. A locale that breaks one of the two
 * length rules lands in the collector like any other fault, at the path of
 * the locale.
 *
 * @param {Array<Object>} richTexts - What `readRichText` collected, in the
 *   order the Blocks stand in.
 * @param {HeroValidationErrors} errors - The run's collector.
 * @returns {Promise<void>}
 */
async function sanitizeRichTexts(richTexts, errors) {
  for (const { field, html, target, locale } of richTexts) {
    try {
      target[locale] = await sanitizeHeroRichText(html, field);
    } catch (error) {
      errors.absorb(error);
    }
  }
}

/**
 * The stored form of a Hero Layout: every default filled, every rich-text
 * locale sanitised, every derived media key dropped, every fault answered at
 * its JSON path.
 *
 * @param {?Object} input - What the client sent. `null` is the reset to the
 *   Default Hero Layout and passes straight through — the default is derived
 *   on the way out, so a Catalog that was never touched keeps following
 *   whatever the default becomes.
 * @param {string} [field] - Where the layout sits in the request body:
 *   `heroLayout` on the catalog PUT and on the hero-layout routes. Every
 *   reported path starts here.
 * @returns {Promise<?Object>} The layout as it is stored.
 * @throws {ValidationError} With one detail per fault, JSON paths as fields.
 */
async function normalizeHeroLayout(input, field = "heroLayout") {
  if (input === null || input === undefined) {
    return null;
  }

  const errors = new HeroValidationErrors();
  const collectors = { references: [], richTexts: [] };

  const layout = readHeroLayout(input, field, errors, collectors);

  // Sanitising and the media library are only reached once the shape is
  // sound. Both would otherwise answer at the wrong moment: a lookup for a
  // reference that is malformed anyway names the wrong fault, and a length
  // rule measured after the whole layout was walked would arrive behind
  // faults that stand later in the body than it does. It also keeps jsdom off
  // a request that is refused either way.
  if (!errors.hasErrors()) {
    await sanitizeRichTexts(collectors.richTexts, errors);
    errors.throwIfAny();
    await MediaReferenceGuard.assertHeroLayoutStorable(collectors.references);
  }

  errors.throwIfAny();

  return layout;
}

